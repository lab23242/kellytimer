// Extracts the landscape generator from vendor/shan-shui-inf/index.html into
// src/shanshui/upstream.js as a factory function, keeping the drawing code verbatim.
//
// What is kept: the <script> blocks PRNG, PerlinNoise, PolyTools, Util and the main
// generator block, cut just before its DOM/mouse/view code.
// What is dropped: URL-query seed parsing, the SVG downloader, the settings/scroll UI,
// inline <body> scripts and the background-canvas script (re-implemented in engine.js).
//
// The only textual change is a `var` line declaring upstream's implicit globals so the
// code runs in strict mode (ES modules are strict). Math, window and console are passed
// in as parameters, so upstream's `Math.random = ...` override stays inside the factory.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const vendorDir = resolve(root, "vendor/shan-shui-inf");
const html = readFileSync(resolve(vendorDir, "index.html"), "utf8");

// Implicit globals assigned without `var` in upstream (found with eslint no-undef).
const IMPLICIT_GLOBALS = ["MEM", "reso", "vtxlist", "vtxlist0", "vtxlist1"];
const KEEP_IDS = ["PRNG", "PerlinNoise", "PolyTools", "Util"];
const MAIN_BLOCK_MARKER = 'console.log("************************************************");';
const MAIN_BLOCK_CUT = 'document.addEventListener("mousemove", onMouseUpdate, false);';

const blocks = [...html.matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/g)].map((m) => ({
  id: (m[1].match(/id="([^"]+)"/) || [])[1] || null,
  body: m[2],
}));

const parts = [];
for (const id of KEEP_IDS) {
  const block = blocks.find((b) => b.id === id);
  if (!block) throw new Error(`upstream block #${id} not found`);
  parts.push(`  // ---- upstream <script id="${id}"> ----${block.body}`);
}
const main = blocks.find((b) => b.id === null && b.body.includes(MAIN_BLOCK_MARKER));
if (!main) throw new Error("upstream main generator block not found");
const cut = main.body.indexOf(MAIN_BLOCK_CUT);
if (cut < 0) throw new Error("upstream DOM cut marker not found");
parts.push(`  // ---- upstream main <script> (up to the DOM/view code) ----${main.body.slice(0, cut)}`);

// First word of UPSTREAM_COMMIT: the upstream commit the vendored copy was taken from.
const commit = readFileSync(resolve(vendorDir, "UPSTREAM_COMMIT"), "utf8").trim().split(/\s+/)[0];

const out = `// AUTO-GENERATED by scripts/extract-upstream.mjs from vendor/shan-shui-inf/index.html
// (upstream commit ${commit}). Do not edit by hand: run \`npm run extract\`.
//
// shan-shui-inf, Copyright (c) 2018 Lingdong Huang. MIT License, see
// vendor/shan-shui-inf/LICENSE and THIRD_PARTY_LICENSES.md.
/* eslint-disable */
export function createUpstream(Math, window, console) {
  // upstream implicit globals, declared so the verbatim code runs in strict mode
  var ${IMPLICIT_GLOBALS.join(", ")};
${parts.join("\n")}
  return { Prng, Noise, PolyTools, Mount, Arch, Man, Tree, water, mountplanner, chunkloader, MEM };
}
`;

writeFileSync(resolve(root, "src/shanshui/upstream.js"), out);
console.log(`wrote src/shanshui/upstream.js (${(out.length / 1024).toFixed(0)} KB, upstream ${commit.slice(0, 7)})`);
